import json
import os
import tempfile
import numpy as np
from pathlib import Path
from datetime import timedelta

from varuna_contracts.schemas import VesselTrack, AISPoint, VesselType
from varuna_contracts.evidence import Provenance
from varuna_source_adapters.protocol import SourceAdapter, SourceQuery, FetchResult

class MockAisAdapter(SourceAdapter):
    """Returns synthetic AIS tracks."""
    
    MOCK_VERSION = "mock-v1"

    @property
    def source_id(self) -> str:
        return "ais.mock"

    def fetch(self, query: SourceQuery) -> FetchResult:
        seed = int(abs(query.bbox.min_lon * 1000) + query.time_start.year) % (2**31)
        rng = np.random.default_rng(seed)
        
        n_tracks = rng.integers(5, 12)
        tracks = []
        vessel_types = [VesselType.TANKER, VesselType.CARGO, VesselType.FISHING]
        
        for i in range(n_tracks):
            vtype = vessel_types[i % len(vessel_types)]
            lon = rng.uniform(query.bbox.min_lon, query.bbox.max_lon)
            lat = rng.uniform(query.bbox.min_lat, query.bbox.max_lat)
            
            vu = rng.normal(0, 0.05)
            vv = rng.normal(0, 0.05)
            
            points = []
            curr_time = query.time_start
            while curr_time <= query.time_end:
                points.append(AISPoint(
                    timestamp=curr_time,
                    lon=lon,
                    lat=lat,
                    sog_knots=float(rng.uniform(4.0, 15.0)),
                    heading_deg=float(rng.uniform(0.0, 360.0))
                ))
                lon += vu
                lat += vv
                curr_time += timedelta(minutes=30)
                
            tracks.append(VesselTrack(
                mmsi=f"MOCK_MMSI_{seed}_{i:04d}",
                vessel_type=vtype,
                points=points
            ))
            
        temp_dir = Path(tempfile.gettempdir()) / "varuna_mocks"
        temp_dir.mkdir(parents=True, exist_ok=True)
        
        out_path = temp_dir / f"ais_{seed}.json"
        with open(out_path, "w") as f:
            json.dump([t.model_dump(mode="json") for t in tracks], f)
            
        return FetchResult(
            artifact_path=str(out_path),
            provenance=Provenance(
                source_id=self.source_id,
                source_version=self.MOCK_VERSION,
                notes="Generated by MockAisAdapter"
            ),
            is_simulated=True
        )

    def health_check(self) -> bool:
        return True
