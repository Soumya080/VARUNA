import os
import tempfile
import numpy as np
from pathlib import Path

from varuna_contracts.evidence import Provenance
from varuna_source_adapters.protocol import SourceAdapter, SourceQuery, FetchResult

class MockEra5Adapter(SourceAdapter):
    """Returns synthetic wind field. is_simulated=True always."""

    MOCK_VERSION = "mock-v1"

    @property
    def source_id(self) -> str:
        return "era5.mock"

    def fetch(self, query: SourceQuery) -> FetchResult:
        seed = int(query.bbox.max_lat * 1000) % (2**31)
        rng = np.random.default_rng(seed)
        
        n_points = 20
        lons = np.linspace(query.bbox.min_lon, query.bbox.max_lon, n_points)
        lats = np.linspace(query.bbox.min_lat, query.bbox.max_lat, n_points)
        
        # Wind: 5 m/s uniform roughly
        u10 = 5.0 + rng.normal(0, 0.5, (n_points, n_points))
        v10 = 2.0 + rng.normal(0, 0.5, (n_points, n_points))
        
        temp_dir = Path(tempfile.gettempdir()) / "varuna_mocks"
        temp_dir.mkdir(parents=True, exist_ok=True)
        
        out_path = temp_dir / f"era5_{seed}.npz"
        np.savez(out_path, lon=lons, lat=lats, u10=u10, v10=v10)
        
        return FetchResult(
            artifact_path=str(out_path),
            provenance=Provenance(
                source_id=self.source_id,
                source_version=self.MOCK_VERSION,
                notes="Generated by MockEra5Adapter"
            ),
            is_simulated=True
        )

    def health_check(self) -> bool:
        return True
