import os
import tempfile
import numpy as np
from pathlib import Path

from varuna_contracts.evidence import Provenance
from varuna_source_adapters.protocol import SourceAdapter, SourceQuery, FetchResult

class MockCmemsAdapter(SourceAdapter):
    """Returns synthetic current field. is_simulated=True always."""

    MOCK_VERSION = "mock-v1"

    @property
    def source_id(self) -> str:
        return "cmems.mock"

    def fetch(self, query: SourceQuery) -> FetchResult:
        # Generate deterministic 2D current field as numpy arrays
        # Shape: (20, 20) grid covering query.bbox
        seed = int(query.bbox.min_lon * 1000) % (2**31)
        rng = np.random.default_rng(seed)
        
        # Simple spatial structure: u = 0.1 * sin(lon), v = 0.05 * cos(lat)
        n_points = 20
        lons = np.linspace(query.bbox.min_lon, query.bbox.max_lon, n_points)
        lats = np.linspace(query.bbox.min_lat, query.bbox.max_lat, n_points)
        lon_grid, lat_grid = np.meshgrid(lons, lats)
        
        u = 0.1 * np.sin(lon_grid) + rng.normal(0, 0.01, (n_points, n_points))
        v = 0.05 * np.cos(lat_grid) + rng.normal(0, 0.01, (n_points, n_points))
        
        # Save as .npz to temp dir
        temp_dir = Path(tempfile.gettempdir()) / "varuna_mocks"
        temp_dir.mkdir(parents=True, exist_ok=True)
        
        out_path = temp_dir / f"cmems_{seed}.npz"
        np.savez(out_path, lon=lons, lat=lats, u=u, v=v)
        
        return FetchResult(
            artifact_path=str(out_path),
            provenance=Provenance(
                source_id=self.source_id,
                source_version=self.MOCK_VERSION,
                notes="Generated by MockCmemsAdapter"
            ),
            is_simulated=True
        )

    def health_check(self) -> bool:
        return True
